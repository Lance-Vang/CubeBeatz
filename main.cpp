// Displays the player's final song results.
void ShowResults(HWND hwnd)
{
    // Calculate the player's accuracy.
    int totalNotes = hitCount + missCount;

    double accuracy = 0.0;

    if (totalNotes > 0)
    {
        accuracy = (static_cast<double>(hitCount) / totalNotes) * 100.0;
    }

    // Determine the player's final rank.
    wchar_t rank = L'D';

    if (accuracy >= 95.0)
        rank = L'S';
    else if (accuracy >= 90.0)
        rank = L'A';
    else if (accuracy >= 80.0)
        rank = L'B';
    else if (accuracy >= 70.0)
        rank = L'C';

    // Format the accuracy percentage.
    wchar_t accuracyText[64];
    swprintf_s(accuracyText, L"Accuracy: %.2f%%", accuracy);

    // Update the Results screen labels.
    SetWindowText(resultsScoreLabel,
        (L"Score: " + std::to_wstring(score)).c_str());

    SetWindowText(resultsAccuracyLabel, accuracyText);

    SetWindowText(resultsComboLabel,
        (L"Max Combo: " + std::to_wstring(maxCombo)).c_str());

    SetWindowText(resultsHitsLabel,
        (L"Notes Hit: " + std::to_wstring(hitCount)).c_str());

    SetWindowText(resultsMissesLabel,
        (L"Misses: " + std::to_wstring(missCount)).c_str());

    wchar_t rankText[32];
    swprintf_s(rankText, L"RANK: %c", rank);

    SetWindowText(resultsRankLabel, rankText);

    // Hide the gameplay HUD.
    ShowWindow(scoreLabel, SW_HIDE);
    ShowWindow(comboLabel, SW_HIDE);
    ShowWindow(missLabel, SW_HIDE);
    ShowWindow(judgmentLabel, SW_HIDE);
    ShowWindow(pauseLabel, SW_HIDE);
    ShowWindow(countdownLabel, SW_HIDE);

    // Hide the song selection controls.
    ShowWindow(songListBox, SW_HIDE);
    ShowWindow(playButton, SW_HIDE);

    // Display the Results screen.
    ShowWindow(resultsTitleLabel, SW_SHOW);
    ShowWindow(resultsScoreLabel, SW_SHOW);
    ShowWindow(resultsAccuracyLabel, SW_SHOW);
    ShowWindow(resultsComboLabel, SW_SHOW);
    ShowWindow(resultsHitsLabel, SW_SHOW);
    ShowWindow(resultsMissesLabel, SW_SHOW);
    ShowWindow(resultsRankLabel, SW_SHOW);
    ShowWindow(replayButton, SW_SHOW);
    ShowWindow(songSelectButton, SW_SHOW);

    // Update the window title.
    SetWindowText(hwnd, L"CubeBeatz | Results");
}




// Opens a Windows file picker so the player can select a song.
bool SelectMusicFile(std::wstring& selectedFile)
{
    // Allocate the file path buffer on the heap instead of the stack.
    std::vector<wchar_t> filePath(32768, L'\0');

    // Configure the Windows file selection dialog.
    OPENFILENAMEW dialog = {};
    dialog.lStructSize = sizeof(dialog);
    dialog.hwndOwner = nullptr;

    dialog.lpstrFilter =
        L"Audio Files (*.mp3;*.wav)\0*.mp3;*.wav\0"
        L"MP3 Files (*.mp3)\0*.mp3\0"
        L"WAV Files (*.wav)\0*.wav\0"
        L"All Files (*.*)\0*.*\0";

    // Connect the file picker to our buffer.
    dialog.lpstrFile = filePath.data();
    dialog.nMaxFile = static_cast<DWORD>(filePath.size());
    dialog.lpstrTitle = L"Select a Song for CubeBeatz";

    dialog.Flags =
        OFN_FILEMUSTEXIST |
        OFN_PATHMUSTEXIST |
        OFN_NOCHANGEDIR;

    // Display the file picker.
    if (GetOpenFileNameW(&dialog))
    {
        selectedFile = filePath.data();
        return true;
    }

    // The player did not select a file.
    return false;
}


bool CompileShader(const wchar_t* filename, const char* entryPoint, const char* shaderModel, ID3DBlob** shaderblob) {
	ID3DBlob* errorBlob = nullptr;

    HRESULT result = D3DCompileFromFile(filename, nullptr, D3D_COMPILE_STANDARD_FILE_INCLUDE, entryPoint, shaderModel,D3DCOMPILE_ENABLE_STRICTNESS, 0, shaderblob, &errorBlob);

    if (FAILED(result)) {
        if (errorBlob != nullptr) {
            MessageBoxA(nullptr,(const char*)errorBlob->GetBufferPointer(),
                "Shader Compilation Error",MB_OK | MB_ICONERROR);
            errorBlob->Release();
        }
        return false;
	}

    if (errorBlob != nullptr) {
        errorBlob->Release();
    }
	return true;
}

//Creates Direct3D shader objects
bool CreateShaders() {
    if (device == nullptr ||
        vertexShaderBlob == nullptr ||
        pixelShaderBlob == nullptr) {
        return false;
    }

    HRESULT result = device -> CreateVertexShader(vertexShaderBlob->GetBufferPointer(), vertexShaderBlob->GetBufferSize(), nullptr, &vertexShader);
    if (FAILED(result)) {
        return false;
    }
    result = device->CreatePixelShader(pixelShaderBlob->GetBufferPointer(), pixelShaderBlob->GetBufferSize(), nullptr, &pixelShader);
    if (FAILED(result)) {
        return false;
    }
	return true;
}

